// evalscene checks what Muse Spark reads in real photos that matter for a
// flash-flood warning: debris flows (the deadliest case) against muddy but
// ordinary floods, debris carried or left behind, and damaged houses.
//
// Cases and their licences are in eval/scene/cases.json; the images live under
// data/raw (not in the repository). Answers are cached next to each image, so a
// rerun costs nothing.
//
//	MODEL_API_KEY=... go run ./cmd/evalscene -out ../eval/results/scene-2026-10
package main

import (
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"time"

	"github.com/spartanoscar/vigiax/server/internal/meta"
	"github.com/spartanoscar/vigiax/server/internal/scene"
)

type testCase struct {
	File       string `json:"file"`
	DebrisFlow bool   `json:"debris_flow"`
	Expect     struct {
		DebrisKinds []string `json:"debris_kinds"`
		Structures  string   `json:"structures"`
	} `json:"expect"`
	Note    string `json:"note"`
	Source  string `json:"source"`
	License string `json:"license"`
	Author  string `json:"author"`
}

func main() {
	cases := flag.String("cases", "../eval/scene/cases.json", "labelled cases")
	raw := flag.String("raw", "../data/raw", "image folder")
	out := flag.String("out", "", "results directory")
	model := flag.String("model", scene.DefaultModel, "Muse Spark model")
	effort := flag.String("effort", scene.DefaultEffort, "reasoning effort")
	flag.Parse()
	key := os.Getenv("MODEL_API_KEY")
	if key == "" || *out == "" {
		flag.Usage()
		os.Exit(2)
	}
	b, err := os.ReadFile(*cases)
	check(err)
	var cs []testCase
	check(json.Unmarshal(b, &cs))
	check(os.MkdirAll(*out, 0o755))
	c := meta.NewClient(key)

	var rows []string
	var tp, fp, fn, tn, okKinds, nKinds, okStruct, nStruct int
	var cost float64
	floors := map[int]int{}
	evacFlows := 0
	levelNames := []string{"—", "attention", "alert", "evacuate"}
	for _, tc := range cs {
		img := filepath.Join(*raw, tc.File)
		cache := strings.TrimSuffix(img, filepath.Ext(img)) + "." + *model + "-" + *effort + ".scene.json"
		var saved struct {
			scene.Reading
			CostUSD float64 `json:"cost_usd"`
		}
		if b, err := os.ReadFile(cache); err == nil {
			check(json.Unmarshal(b, &saved))
		} else {
			jpeg, err := os.ReadFile(img)
			check(err)
			ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
			got, err := scene.Read(ctx, c, *model, *effort, jpeg)
			cancel()
			check(err)
			saved.Reading, saved.CostUSD = *got, got.CostUSD
			b, _ := json.MarshalIndent(saved, "", "  ")
			check(os.WriteFile(cache, b, 0o644))
		}
		r := saved.Reading
		cost += saved.CostUSD
		said := r.Flow == "debris_flow"
		switch {
		case said && tc.DebrisFlow:
			tp++
		case said && !tc.DebrisFlow:
			fp++
		case !said && tc.DebrisFlow:
			fn++
		default:
			tn++
		}
		var notes []string
		for _, k := range tc.Expect.DebrisKinds {
			nKinds++
			if slices.Contains(r.DebrisKinds, k) {
				okKinds++
			} else {
				notes = append(notes, "missed "+k)
			}
		}
		if tc.Expect.Structures != "" {
			nStruct++
			if slices.Contains(strings.Split(tc.Expect.Structures, "|"), r.Structures) {
				okStruct++
			} else {
				notes = append(notes, "structures "+r.Structures)
			}
		}
		mark := "✓"
		if said != tc.DebrisFlow || len(notes) > 0 {
			mark = "✗"
		}
		floor, _ := r.Floor()
		floors[floor]++
		if tc.DebrisFlow && floor == 3 {
			evacFlows++
		}
		rows = append(rows, fmt.Sprintf("| %s | %s | %v | %s | %s | %s | **%s** | %s | %s |", mark, filepath.Base(tc.File), tc.DebrisFlow, r.Flow,
			strings.Join(r.DebrisKinds, ", "), r.Structures, levelNames[floor], strings.Join(notes, "; "), strings.ReplaceAll(r.Summary, "|", "/")))
		log.Printf("%s %-60s flow=%s kinds=%v structures=%s", mark, filepath.Base(tc.File), r.Flow, r.DebrisKinds, r.Structures)
	}

	md := fmt.Sprintf(`# Muse Spark scene reading on real photos

Generated by `+"`go run ./cmd/evalscene`"+` (server/) on %s with %s (effort %s). Cases, sources and licences:
`+"`eval/scene/cases.json`"+`.

| | |
|---|---|
| Debris flow in progress | %d of %d found; %d false alarm(s) in %d other photos |
| Debris kinds expected and seen | %d of %d |
| Damaged structures | %d of %d |
| Scene rules (Reading.Floor) | debris flows in progress → evacuate: %d of %d; all photos: evacuate %d, alert %d, none %d |
| Model cost | $%.4f (a rerun from the cache costs nothing) |

| | Image | Debris flow (label) | flow | debris_kinds | structures | Scene rule | Misses | Summary |
|---|---|---|---|---|---|---|---|---|
%s

Small and hand-picked: it checks the model can tell the deadly case apart, not how often it does in the field.
`, time.Now().UTC().Format(time.DateOnly), *model, *effort, tp, tp+fn, fp, fp+tn, okKinds, nKinds, okStruct, nStruct, evacFlows, tp+fn, floors[3], floors[2], floors[0]+floors[1], cost, strings.Join(rows, "\n"))
	check(os.WriteFile(filepath.Join(*out, "README.md"), []byte(md), 0o644))
	fmt.Print(md)
}

func check(err error) {
	if err != nil {
		log.Fatal(err)
	}
}
