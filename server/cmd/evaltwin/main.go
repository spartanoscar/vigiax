// evaltwin scores runs of the digital twin recorded by the service: how long
// before the water reached each line the station raised the alert, with the
// rules alone and with the agent. The twin sends its real level with every
// frame (truth_cm, kept as the reading's reference), so the truth is known.
//
// A run is one station of the twin, from its last restart: a calm start, then
// a flash flood with or without people on the banks or a debris flow. The
// service ran the rules and the agent live; the rules alone are replayed here
// on the same readings, with the same code.
//
//	go run ./cmd/evaltwin -data DATA_DIR/stations -runs plain=twin-evpla1,people=twin-evppl1 \
//	    -out ../eval/results/twin-2026-10
package main

import (
	"bufio"
	"encoding/csv"
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"math"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/spartanoscar/vigiax/server/internal/agent"
	"github.com/spartanoscar/vigiax/server/internal/alert"
	"github.com/spartanoscar/vigiax/server/internal/station"
)

type run struct {
	Name, ID string
	Start    time.Time // the run's restart
	Readings []station.Reading
	Live     []alert.Event // what the service raised: rules, scene rules and agent
	Rules    []alert.Event // the rules alone, replayed
	Agent    []agent.Result
}

func main() {
	data := flag.String("data", "", "the service's stations directory (DATA_DIR/stations)")
	runs := flag.String("runs", "", "name=station,... in the order to report")
	out := flag.String("out", "", "results directory")
	flag.Parse()
	if *data == "" || *runs == "" || *out == "" {
		flag.Usage()
		os.Exit(2)
	}
	check(os.MkdirAll(*out, 0o755))
	c := alert.TwinDefaults()
	var rs []run
	for _, nv := range strings.Split(*runs, ",") {
		name, id, ok := strings.Cut(nv, "=")
		if !ok {
			log.Fatalf("run %q: want name=station", nv)
		}
		r := run{Name: name, ID: id}
		for _, e := range readEvents(filepath.Join(*data, id+".alerts.jsonl")) {
			if e.Kind == "restart" {
				r.Start, r.Live = e.T, nil
				continue
			}
			r.Live = append(r.Live, e)
		}
		st, err := station.Open(*data, id)
		check(err)
		r.Readings = st.Readings(r.Start)
		var state alert.State
		for _, rd := range r.Readings {
			if e := state.Step(&c, st.Observe(&c, rd, r.Start)); e != nil {
				r.Rules = append(r.Rules, *e)
			}
		}
		r.Agent = readRuns(filepath.Join(*data, id+".agent.jsonl"), r.Start)
		rs = append(rs, r)
	}
	report(*out, &c, rs)
}

// truthAt is the first reading whose real level is at or above the line.
func truthAt(r run, lineCm float64) (time.Time, bool) {
	for _, rd := range r.Readings {
		if rd.RefCm != nil && *rd.RefCm >= lineCm {
			return rd.T, true
		}
	}
	return time.Time{}, false
}

func firstRaise(events []alert.Event, l alert.Level) (alert.Event, bool) {
	for _, e := range events {
		if (e.Kind == "raise") && e.To >= l {
			return e, true
		}
	}
	return alert.Event{}, false
}

func report(out string, c *alert.Config, rs []run) {
	var md strings.Builder
	fmt.Fprintf(&md, "# Digital twin — how early the alert goes out, rules alone and with the agent\n\n")
	fmt.Fprintf(&md, "Generated by `go run ./cmd/evaltwin` (server/) on %s. **Simulated**: the creek, the flood, the people and the debris are the digital twin's; SAM 3.1, Muse Spark and Muse Spark Open are the real models, called by the service as in production.\n\n", time.Now().Format("2006-01-02"))
	fmt.Fprintf(&md, "Each run starts calm, then a 2-minute flash flood takes the water from about 45 cm to 320 cm. The camera node sends a frame every 5 s. The twin's lines: attention %s, alert %s, evacuate %s, each confirmed on %d readings. Lead time is how long before the real water reached the line the station raised to that level (or higher); negative is after.\n\n",
		ruleText(c.Rules.Attention), ruleText(c.Rules.Alert), ruleText(c.Rules.Evacuate), c.Confirm)
	fmt.Fprintf(&md, "| Run | Level | Water reached the line | Rules alone | Rules + agent | Gain |\n|---|---|---|---|---|---|\n")

	w, err := os.Create(filepath.Join(out, "events.csv"))
	check(err)
	cw := csv.NewWriter(w)
	cw.Write([]string{"run", "mode", "time_utc", "seconds_from_start", "kind", "from", "to", "by", "level_cm", "reason"})
	for _, r := range rs {
		for _, mode := range []struct {
			name string
			ev   []alert.Event
		}{{"rules", r.Rules}, {"live", r.Live}} {
			for _, e := range mode.ev {
				lv := ""
				if e.LevelCm != nil {
					lv = fmt.Sprintf("%.0f", *e.LevelCm)
				}
				cw.Write([]string{r.Name, mode.name, e.T.UTC().Format(time.RFC3339Nano), fmt.Sprintf("%.1f", e.T.Sub(r.Start).Seconds()),
					e.Kind, e.From.String(), e.To.String(), e.By, lv, e.Reason})
			}
		}
		for l := alert.Attention; l <= alert.Evacuate; l++ {
			line := c.Rule(l).LevelCm
			if line == nil {
				continue
			}
			tt, tok := truthAt(r, *line)
			cell := func(events []alert.Event) (string, float64, bool) {
				e, ok := firstRaise(events, l)
				if !ok {
					return "not raised", 0, false
				}
				by := "rules"
				if e.By != "" {
					by = e.By
				}
				if !tok {
					return fmt.Sprintf("at %.0f s (%s)", e.T.Sub(r.Start).Seconds(), by), 0, false
				}
				lead := tt.Sub(e.T).Seconds()
				return fmt.Sprintf("%+.0f s (%s)", lead, by), lead, true
			}
			rc, rl, rok := cell(r.Rules)
			lc, ll, lok := cell(r.Live)
			gain := "—"
			if rok && lok {
				gain = fmt.Sprintf("%+.0f s", ll-rl)
			}
			truth := "never"
			if tok {
				truth = fmt.Sprintf("%.0f s after start", tt.Sub(r.Start).Seconds())
			}
			fmt.Fprintf(&md, "| %s | %s (%.0f cm) | %s | %s | %s | %s |\n", r.Name, l, *line, truth, rc, lc, gain)
		}
	}
	cw.Flush()
	check(w.Close())

	fmt.Fprintf(&md, "\n## What the agent saw and decided\n\n| Run | Woken by | Scene (Muse Spark) | Decision (Muse Spark Open) | Verified | Seconds | Cost |\n|---|---|---|---|---|---|---|\n")
	var usd, sec float64
	n := 0
	for _, r := range rs {
		for _, a := range r.Agent {
			sc := ""
			if a.Facts.Scene != nil {
				sc = a.Facts.Scene.Summary
			}
			d := "no verified answer: the rule level stands"
			if a.Decision != nil {
				d = fmt.Sprintf("%s → %s: %s", a.Decision.Action, a.Decision.Level, a.Decision.Reason)
			}
			fmt.Fprintf(&md, "| %s | %s %s → %s at %.0f s | %s | %s | %v | %.1f | $%.4f |\n", r.Name, a.Facts.Woke.Kind, a.Facts.Woke.From, a.Facts.Woke.To,
				a.Facts.Woke.T.Sub(r.Start).Seconds(), cellText(sc), cellText(d), a.Verified, a.Seconds, a.CostUSD)
			usd += a.CostUSD
			sec += a.Seconds
			n++
		}
	}
	var samUSD float64
	frames := 0
	for _, r := range rs {
		for _, rd := range r.Readings {
			samUSD += rd.CostUSD
			frames++
		}
	}
	fmt.Fprintf(&md, "\nModel cost of these runs: SAM 3.1 $%.4f for %d frames; agent with scene reading $%.4f for %d runs (mean %.1f s).\n\n",
		samUSD, frames, usd, n, sec/math.Max(1, float64(n)))
	fmt.Fprintf(&md, "The scene rules (a debris flow, a dammed channel, a house in the water → evacuate) run on Muse Spark's reading before the agent decides; their raises show as \"scene\". A language model can answer differently on another run: these are the answers it gave.\n\nPer-event values: events.csv.\n")
	check(os.WriteFile(filepath.Join(out, "README.md"), []byte(md.String()), 0o644))
	fmt.Print(md.String())
}

func readEvents(path string) []alert.Event {
	f, err := os.Open(path)
	check(err)
	defer f.Close()
	var es []alert.Event
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		var e alert.Event
		if json.Unmarshal(sc.Bytes(), &e) == nil {
			es = append(es, e)
		}
	}
	return es
}

func readRuns(path string, since time.Time) []agent.Result {
	f, err := os.Open(path)
	if err != nil {
		return nil
	}
	defer f.Close()
	var rs []agent.Result
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 0, 64<<10), 1<<20)
	for sc.Scan() {
		var r agent.Result
		if json.Unmarshal(sc.Bytes(), &r) == nil && !r.Facts.Now.Before(since) {
			rs = append(rs, r)
		}
	}
	return rs
}

func ruleText(r alert.Rule) string {
	var p []string
	if r.LevelCm != nil {
		p = append(p, fmt.Sprintf("%.0f cm", *r.LevelCm))
	}
	if r.RiseCmPerMin != nil {
		p = append(p, fmt.Sprintf("%.0f cm/min", *r.RiseCmPerMin))
	}
	return strings.Join(p, " or ")
}

func cellText(s string) string { return strings.ReplaceAll(s, "|", "/") }

func check(err error) {
	if err != nil {
		log.Fatal(err)
	}
}
